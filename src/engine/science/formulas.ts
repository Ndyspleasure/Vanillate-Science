/**
 * Formula registry for physics, chemistry, astronomy, engineering and geometry.
 *
 * Each formula is stored once as an equation string; the formula solver can solve it for
 * any of its variables (symbolically when possible, otherwise after substitution), with
 * units converted to SI and dimensional consistency checked.
 * References point to open textbooks (OpenStax) rather than invented chapter numbers.
 */
import { REFERENCES } from "../steps/builder";
import type { Reference } from "../steps/types";

export type Constraint = "positive" | "nonnegative" | "angle" | "unit-interval" | "below-c" | "any";

export interface FormulaVariable {
  s: string;
  name: string;
  unit: string;
  latex?: string;
  constraint?: Constraint;
  /** Key into CONSTANTS: value is fixed (not solvable), shown in steps. */
  constant?: string;
  /** Default value (editable), e.g. g = 9.80665 m/s². */
  defaultValue?: string;
}

export type FormulaDomain = "fisika" | "kimia" | "astronomi" | "teknik" | "geometri";

export interface FormulaDef {
  id: string;
  name: string;
  domain: FormulaDomain;
  topic: string;
  equation: string;
  variables: FormulaVariable[];
  description: string;
  assumptions?: string[];
  reference: Reference;
  example: { solveFor: string; values: Record<string, string> };
}

