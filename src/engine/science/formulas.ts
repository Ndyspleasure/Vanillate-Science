const v = (
  s: string,
  name: string,
  unit: string,
  extra: Partial<FormulaVariable> = {},
): FormulaVariable => ({ s, name, unit, constraint: "any", ...extra });
const pos = (
  s: string,
  name: string,
  unit: string,
  extra: Partial<FormulaVariable> = {},
): FormulaVariable => v(s, name, unit, { constraint: "positive", ...extra });
const nonneg = (
  s: string,
  name: string,
  unit: string,
  extra: Partial<FormulaVariable> = {},
): FormulaVariable => v(s, name, unit, { constraint: "nonnegative", ...extra });
const angle = (s: string, name: string): FormulaVariable =>
  v(s, name, "°", { constraint: "angle", latex: s === "theta" ? "\\theta" : undefined });
const g = (): FormulaVariable =>
  pos("g", "percepatan gravitasi", "m/s^2", { defaultValue: "9.80665" });

